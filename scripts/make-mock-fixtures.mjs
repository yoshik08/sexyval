// Builds mock/fixtures/collection.json from valorant-api.com: only UUIDs, dates and prices, no art.
// Picks owned items and shop items deterministically, mixing skins with and without videos.
import { writeFileSync } from 'node:fs';

const get = async (p) => (await (await fetch(`https://valorant-api.com/v1/${p}`)).json()).data;
const [weapons, tiers, buddies, sprays, cards, titles, missions, contracts, seasons, themes, bundles] = await Promise.all(
  ['weapons', 'contenttiers', 'buddies', 'sprays', 'playercards', 'playertitles', 'missions', 'contracts', 'seasons', 'themes', 'bundles'].map(get),
);
const PRICE = { Select: 875, Deluxe: 1275, Premium: 1775, Exclusive: 2175, Ultra: 2475 };
const tierName = Object.fromEntries(tiers.map((t) => [t.uuid, t.devName]));
const skins = weapons.flatMap((w) => w.skins.map((s) => ({ ...s, weaponId: w.uuid }))).filter((s) => s.contentTierUuid);
const hasVideo = (s) => s.levels.some((l) => l.streamedVideo) || s.chromas.some((c) => c.streamedVideo);
const withVid = skins.filter(hasVideo);
const noVid = skins.filter((s) => !hasVideo(s));
const every = (arr, n, off = 0) => arr.filter((_, i) => (i + off) % n === 0);

const ownedSkins = [...every(withVid, 9).slice(0, 70), ...every(noVid, 7).slice(0, 50)];
const levels = [];
const chromas = [];
ownedSkins.forEach((s, i) => {
  levels.push(s.levels[0].uuid);
  if (i % 3 === 0) levels.push(...s.levels.slice(1).map((l) => l.uuid));
  if (i % 3 === 0 && s.chromas[1]) chromas.push(s.chromas[1].uuid);
});
const prices = {};
for (const s of skins) prices[s.levels[0].uuid] = PRICE[tierName[s.contentTierUuid]] ?? 1775;

const ownedBuddies = every(buddies, 11).map((b) => ({ id: b.uuid, level: b.levels[0].uuid }));
const ownedSprays = every(sprays.filter((s) => !s.isNullSpray), 9).map((s) => s.uuid);
const ownedCards = every(cards, 8).map((c) => c.uuid);
const ownedTitles = every(titles.filter((t) => t.titleText), 6).map((t) => t.uuid);

// Loadout: owned skin per weapon where possible, otherwise the weapon's default skin.
const guns = weapons.map((w, i) => {
  const mine = ownedSkins.find((s) => s.weaponId === w.uuid);
  const s = mine ?? w.skins.find((x) => x.uuid === w.defaultSkinUuid) ?? w.skins[0];
  const gun = { ID: w.uuid, SkinID: s.uuid, SkinLevelID: s.levels[0].uuid, ChromaID: s.chromas[0].uuid, Attachments: [] };
  if (w.displayName !== 'Melee' && i < 3) Object.assign(gun, { CharmID: ownedBuddies[i].id, CharmLevelID: ownedBuddies[i].level });
  return gun;
});

const now = Date.now();
const acts = seasons.filter((s) => s.type === 'EAresSeasonType::Act');
const currentAct = acts.find((s) => Date.parse(s.startTime) <= now && now < Date.parse(s.endTime)) ?? acts[acts.length - 1];
const seasonContract = contracts.find((c) => c.content.relationType === 'Season' && c.content.relationUuid === currentAct.uuid) ?? contracts.filter((c) => c.content.relationType === 'Season').pop();
const eventContract = contracts.filter((c) => c.content.relationType === 'Event').pop();
const agentContracts = contracts.filter((c) => c.content.relationType === 'Agent').slice(0, 6);
const weeklies = missions.filter((m) => m.type === 'EAresMissionType::Weekly' && m.activationDate).map((m) => ({ id: m.uuid, a: m.activationDate, e: m.expirationDate, target: m.progressToComplete }));
const dailies = missions.filter((m) => m.type === 'EAresMissionType::Daily').map((m) => ({ id: m.uuid, target: m.progressToComplete }));

const out = {
  note: 'Generated by scripts/make-mock-fixtures.mjs. UUIDs/dates/prices only, no assets.',
  owned: { levels, chromas, buddies: ownedBuddies, sprays: ownedSprays, cards: ownedCards, titles: ownedTitles },
  prices,
  shop: {
    daily: [withVid[3], withVid[57], withVid[120], noVid[11]].map((s) => s.levels[0].uuid),
    night: [withVid[200], noVid[40], withVid[260], withVid[310], noVid[80], withVid[333]].map((s) => s.levels[0].uuid),
    bundle: withVid.filter((s) => s.themeUuid === withVid[400].themeUuid).slice(0, 4).map((s) => s.levels[0].uuid),
    bundleAsset: bundles.find((b) => b.displayName === themes.find((t) => t.uuid === withVid[400].themeUuid)?.displayName)?.uuid ?? null,
  },
  loadout: { guns, sprays: ownedSprays.slice(0, 3), card: ownedCards[0], title: ownedTitles[0] },
  progression: {
    act: currentAct.uuid,
    acts: acts.slice(-4).map((a) => a.uuid),
    season: seasonContract?.uuid,
    seasonLevels: seasonContract?.content.chapters.flatMap((c) => c.levels).length ?? 50,
    event: eventContract?.uuid,
    agents: agentContracts.map((c) => c.uuid),
    weeklies,
    dailies,
  },
  sample: { withVideo: withVid[3].displayName, withoutVideo: noVid[11].displayName },
};
writeFileSync('mock/fixtures/collection.json', JSON.stringify(out));
console.log('owned skins', ownedSkins.length, 'levels', levels.length, 'chromas', chromas.length, 'guns', guns.length, 'act', currentAct.displayName, 'weeklies', weeklies.length, out.sample);
